package render

import (
	"bytes"
	"strings"

	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
)

// ChromaCSS returns the stylesheet for highlighted code: the "github" style for
// the light theme and "github-dark" for the dark theme, each scoped to Bootstrap's
// data-bs-theme attribute. It is committed as assets/static/css/chroma.css; a
// test fails when the committed file is stale.
//
// Pattern: Classes, Not Styles
func ChromaCSS() string {
	var out strings.Builder
	out.WriteString("/* Generated by `go generate ./internal/infrastructure/api/web/render`. Do not edit. */\n")

	for _, theme := range []struct{ attr, style string }{{"light", "github"}, {"dark", "github-dark"}} {
		var css bytes.Buffer
		formatter := chromahtml.New(chromahtml.WithClasses(true))
		if err := formatter.WriteCSS(&css, styles.Get(theme.style)); err != nil {
			panic("render: writing chroma css: " + err.Error()) // only fails on a broken writer
		}
		scope := `[data-bs-theme="` + theme.attr + `"] .chroma`
		out.WriteString("\n/* " + theme.style + " */\n")
		for line := range strings.Lines(css.String()) {
			if strings.HasPrefix(line, "/* Background */") {
				continue // the .bg class is not used; .chroma carries the background
			}
			out.WriteString(strings.ReplaceAll(line, ".chroma", scope))
		}
	}
	return out.String()
}
